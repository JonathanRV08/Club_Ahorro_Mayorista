CREATE OR REPLACE PACKAGE BODY FIDE_CURSORES_PKG AS
    PROCEDURE GENERAR_LISTADO(P_TIPO IN VARCHAR2, P_TEXTO OUT CLOB,
        P_FILAS OUT NUMBER, P_FILTRO IN NUMBER) IS
        CURSOR C_SOCIOS_ACTIVOS IS
            SELECT ID_SOCIO || ' | ' || NOMBRE || ' ' || APELLIDOS AS LINEA FROM FIDE_SOCIOS_TB WHERE ESTADO='ACTIVO' ORDER BY ID_SOCIO;

        CURSOR C_SOCIOS_INACTIVOS IS
            SELECT ID_SOCIO || ' | ' || NOMBRE || ' ' || APELLIDOS AS LINEA FROM FIDE_SOCIOS_TB WHERE ESTADO='INACTIVO' ORDER BY ID_SOCIO;

        CURSOR C_MEMBRESIAS_VIGENTES IS
            SELECT ID_MEMBRESIA || ' | ' || SOCIO || ' | ' || TO_CHAR(FECHA_VENCIMIENTO,'YYYY-MM-DD') AS LINEA FROM FIDE_MEMBRESIAS_VW WHERE VIGENCIA='VIGENTE' ORDER BY FECHA_VENCIMIENTO;

        CURSOR C_MEMBRESIAS_VENCIDAS IS
            SELECT ID_MEMBRESIA || ' | ' || SOCIO || ' | ' || TO_CHAR(FECHA_VENCIMIENTO,'YYYY-MM-DD') AS LINEA FROM FIDE_MEMBRESIAS_VW WHERE VIGENCIA='VENCIDA' ORDER BY FECHA_VENCIMIENTO;

        CURSOR C_MEMBRESIAS_POR_VENCER IS
            SELECT ID_MEMBRESIA || ' | ' || SOCIO || ' | ' || TO_CHAR(FECHA_VENCIMIENTO,'YYYY-MM-DD') AS LINEA FROM FIDE_MEMBRESIAS_VW WHERE VIGENCIA='VIGENTE' AND FECHA_VENCIMIENTO<TRUNC(SYSDATE)+31 ORDER BY FECHA_VENCIMIENTO;

        CURSOR C_PRODUCTOS_CATEGORIA IS
            SELECT P.CODIGO_PRODUCTO || ' | ' || P.NOMBRE || ' | ' || C.NOMBRE AS LINEA FROM FIDE_PRODUCTOS_TB P JOIN FIDE_CATEGORIAS_TB C ON C.ID_CATEGORIA=P.ID_CATEGORIA WHERE (P_FILTRO IS NULL OR P.ID_CATEGORIA=P_FILTRO) ORDER BY C.NOMBRE,P.NOMBRE;

        CURSOR C_PROVEEDORES_PRODUCTO IS
            SELECT PRODUCTO || ' | ' || PROVEEDOR || ' | ' || PRECIO_COMPRA AS LINEA FROM FIDE_PROVEEDORES_PRODUCTOS_VW WHERE (P_FILTRO IS NULL OR ID_PRODUCTO=P_FILTRO) ORDER BY PRODUCTO,PROVEEDOR;

        CURSOR C_INVENTARIO_BAJO IS
            SELECT CODIGO_PRODUCTO || ' | ' || NOMBRE || ' | ' || CANTIDAD_DISPONIBLE || ' / ' || CANTIDAD_MINIMA AS LINEA FROM FIDE_STOCK_BAJO_VW ORDER BY FALTANTE DESC,ID_PRODUCTO;

        CURSOR C_INVENTARIO_AGOTADO IS
            SELECT CODIGO_PRODUCTO || ' | ' || NOMBRE AS LINEA FROM FIDE_INVENTARIOS_VW WHERE CANTIDAD_DISPONIBLE=0 AND ESTADO='ACTIVO' ORDER BY ID_PRODUCTO;

        CURSOR C_MOVIMIENTOS_PRODUCTO IS
            SELECT ID_MOVIMIENTO || ' | ' || TIPO_MOVIMIENTO || ' | ' || CANTIDAD || ' | ' || TO_CHAR(FECHA_MOVIMIENTO,'YYYY-MM-DD HH24:MI') AS LINEA FROM FIDE_MOVIMIENTOS_INVENTARIO_TB WHERE (P_FILTRO IS NULL OR ID_PRODUCTO=P_FILTRO) ORDER BY FECHA_MOVIMIENTO,ID_MOVIMIENTO;

        CURSOR C_VENTAS_CONFIRMADAS IS
            SELECT ID_VENTA || ' | ' || SOCIO || ' | ' || TOTAL AS LINEA FROM FIDE_VENTAS_VW WHERE ESTADO='CONFIRMADA' AND (P_FILTRO IS NULL OR ID_SOCIO=P_FILTRO) ORDER BY FECHA_CONFIRMACION,ID_VENTA;

        CURSOR C_VENTAS_PENDIENTES IS
            SELECT ID_VENTA || ' | ' || SOCIO || ' | ' || TOTAL AS LINEA FROM FIDE_VENTAS_VW WHERE ESTADO='PENDIENTE' ORDER BY FECHA_VENTA,ID_VENTA;

        CURSOR C_VENTAS_ANULADAS IS
            SELECT ID_VENTA || ' | ' || SOCIO || ' | ' || MOTIVO_ANULACION AS LINEA FROM FIDE_VENTAS_VW WHERE ESTADO='ANULADA' ORDER BY FECHA_ANULACION,ID_VENTA;

        CURSOR C_DETALLES_VENTA IS
            SELECT ID_VENTA || ' | ' || NOMBRE || ' | ' || CANTIDAD || ' | ' || SUBTOTAL AS LINEA FROM FIDE_DETALLES_VENTA_VW WHERE (P_FILTRO IS NULL OR ID_VENTA=P_FILTRO) ORDER BY ID_VENTA,ID_DETALLE_VENTA;

        CURSOR C_PRODUCTOS_MAS_VENDIDOS IS
            SELECT CODIGO_PRODUCTO || ' | ' || NOMBRE || ' | ' || UNIDADES_VENDIDAS AS LINEA FROM FIDE_PRODUCTOS_VENDIDOS_VW ORDER BY UNIDADES_VENDIDAS DESC,ID_PRODUCTO;

        PROCEDURE AGREGAR_LINEA(P_LINEA IN VARCHAR2) IS
        BEGIN
            P_TEXTO := P_TEXTO || P_LINEA || CHR(10);
            P_FILAS := P_FILAS+1;
        END;
    BEGIN
        P_TEXTO := NULL;
        P_FILAS := 0;
        CASE UPPER(TRIM(P_TIPO))
            WHEN 'SOCIOS_ACTIVOS' THEN
                FOR R IN C_SOCIOS_ACTIVOS LOOP
                    AGREGAR_LINEA(R.LINEA);
                END LOOP;
            WHEN 'SOCIOS_INACTIVOS' THEN
                FOR R IN C_SOCIOS_INACTIVOS LOOP
                    AGREGAR_LINEA(R.LINEA);
                END LOOP;
            WHEN 'MEMBRESIAS_VIGENTES' THEN
                FOR R IN C_MEMBRESIAS_VIGENTES LOOP
                    AGREGAR_LINEA(R.LINEA);
                END LOOP;
            WHEN 'MEMBRESIAS_VENCIDAS' THEN
                FOR R IN C_MEMBRESIAS_VENCIDAS LOOP
                    AGREGAR_LINEA(R.LINEA);
                END LOOP;
            WHEN 'MEMBRESIAS_POR_VENCER' THEN
                FOR R IN C_MEMBRESIAS_POR_VENCER LOOP
                    AGREGAR_LINEA(R.LINEA);
                END LOOP;
            WHEN 'PRODUCTOS_CATEGORIA' THEN
                FOR R IN C_PRODUCTOS_CATEGORIA LOOP
                    AGREGAR_LINEA(R.LINEA);
                END LOOP;
            WHEN 'PROVEEDORES_PRODUCTO' THEN
                FOR R IN C_PROVEEDORES_PRODUCTO LOOP
                    AGREGAR_LINEA(R.LINEA);
                END LOOP;
            WHEN 'INVENTARIO_BAJO' THEN
                FOR R IN C_INVENTARIO_BAJO LOOP
                    AGREGAR_LINEA(R.LINEA);
                END LOOP;
            WHEN 'INVENTARIO_AGOTADO' THEN
                FOR R IN C_INVENTARIO_AGOTADO LOOP
                    AGREGAR_LINEA(R.LINEA);
                END LOOP;
            WHEN 'MOVIMIENTOS_PRODUCTO' THEN
                FOR R IN C_MOVIMIENTOS_PRODUCTO LOOP
                    AGREGAR_LINEA(R.LINEA);
                END LOOP;
            WHEN 'VENTAS_CONFIRMADAS' THEN
                FOR R IN C_VENTAS_CONFIRMADAS LOOP
                    AGREGAR_LINEA(R.LINEA);
                END LOOP;
            WHEN 'VENTAS_PENDIENTES' THEN
                FOR R IN C_VENTAS_PENDIENTES LOOP
                    AGREGAR_LINEA(R.LINEA);
                END LOOP;
            WHEN 'VENTAS_ANULADAS' THEN
                FOR R IN C_VENTAS_ANULADAS LOOP
                    AGREGAR_LINEA(R.LINEA);
                END LOOP;
            WHEN 'DETALLES_VENTA' THEN
                FOR R IN C_DETALLES_VENTA LOOP
                    AGREGAR_LINEA(R.LINEA);
                END LOOP;
            WHEN 'PRODUCTOS_MAS_VENDIDOS' THEN
                FOR R IN C_PRODUCTOS_MAS_VENDIDOS LOOP
                    AGREGAR_LINEA(R.LINEA);
                END LOOP;
            ELSE RAISE_APPLICATION_ERROR(-20014,'Listado no reconocido.');
        END CASE;
    END GENERAR_LISTADO;
END FIDE_CURSORES_PKG;
/
SHOW ERRORS PACKAGE BODY FIDE_CURSORES_PKG;
