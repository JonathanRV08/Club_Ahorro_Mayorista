CREATE OR REPLACE FUNCTION FIDE_USUARIO_HABILITADO_FN (P_USUARIO IN NUMBER, P_ROL IN VARCHAR2 DEFAULT NULL)
RETURN NUMBER IS
    V_TOTAL NUMBER;
BEGIN
    SELECT COUNT(*) INTO V_TOTAL FROM FIDE_USUARIOS_VW
    WHERE ID_USUARIO=P_USUARIO AND ESTADO='ACTIVO' AND ESTADO_EMPLEADO='ACTIVO'
          AND (P_ROL IS NULL OR ROL=P_ROL OR ROL='ADMIN_SISTEMA');
    RETURN V_TOTAL;
END;
/
