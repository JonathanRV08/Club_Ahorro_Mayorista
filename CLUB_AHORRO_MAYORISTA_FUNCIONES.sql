CREATE OR REPLACE FUNCTION FIDE_FECHA_VENCIMIENTO_FN (P_TIPO IN NUMBER, P_INICIO IN DATE)
RETURN DATE IS
    V_MESES NUMBER;
BEGIN
    SELECT DURACION_MESES INTO V_MESES FROM FIDE_TIPOS_MEMBRESIA_TB WHERE ID_TIPO_MEMBRESIA=P_TIPO;
    RETURN ADD_MONTHS(TRUNC(P_INICIO), V_MESES);
END;
/
SHOW ERRORS FUNCTION FIDE_FECHA_VENCIMIENTO_FN;

CREATE OR REPLACE FUNCTION FIDE_MEMBRESIA_VIGENTE_FN (P_SOCIO IN NUMBER, P_FECHA IN DATE DEFAULT SYSDATE)
RETURN NUMBER IS
    V_TOTAL NUMBER;
BEGIN
    SELECT COUNT(*) INTO V_TOTAL FROM FIDE_MEMBRESIAS_TB
    WHERE ID_SOCIO=P_SOCIO AND ESTADO='REGISTRADA' AND TRUNC(P_FECHA)>=TRUNC(FECHA_INICIO)
          AND TRUNC(P_FECHA)<TRUNC(FECHA_VENCIMIENTO);
    IF V_TOTAL>0 THEN RETURN 1; END IF;
    RETURN 0;
END;
/
SHOW ERRORS FUNCTION FIDE_MEMBRESIA_VIGENTE_FN;

CREATE OR REPLACE FUNCTION FIDE_MEMBRESIA_SOLAPADA_FN (P_SOCIO IN NUMBER, P_INICIO IN DATE, P_FIN IN DATE, P_EXCLUIR IN NUMBER DEFAULT NULL)
RETURN NUMBER IS
    V_TOTAL NUMBER;
BEGIN
    SELECT COUNT(*) INTO V_TOTAL FROM FIDE_MEMBRESIAS_TB
    WHERE ID_SOCIO=P_SOCIO AND ESTADO='REGISTRADA' AND (P_EXCLUIR IS NULL OR ID_MEMBRESIA<>P_EXCLUIR)
          AND TRUNC(FECHA_INICIO)<TRUNC(P_FIN) AND TRUNC(FECHA_VENCIMIENTO)>TRUNC(P_INICIO);
    IF V_TOTAL>0 THEN RETURN 1; END IF;
    RETURN 0;
END;
/
SHOW ERRORS FUNCTION FIDE_MEMBRESIA_SOLAPADA_FN;

