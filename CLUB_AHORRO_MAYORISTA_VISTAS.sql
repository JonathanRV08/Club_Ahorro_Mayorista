CREATE OR REPLACE VIEW FIDE_MEMBRESIAS_VW AS
SELECT M.ID_MEMBRESIA, M.ID_SOCIO, S.IDENTIFICACION, S.NOMBRE || ' ' || S.APELLIDOS AS SOCIO,
       M.ID_TIPO_MEMBRESIA, T.NOMBRE AS TIPO_MEMBRESIA, M.FECHA_INICIO, M.FECHA_VENCIMIENTO, M.ESTADO,
       CASE WHEN M.ESTADO = 'CANCELADA' THEN 'CANCELADA'
            WHEN TRUNC(SYSDATE) < TRUNC(M.FECHA_INICIO) THEN 'FUTURA'
            WHEN TRUNC(SYSDATE) >= TRUNC(M.FECHA_VENCIMIENTO) THEN 'VENCIDA'
            ELSE 'VIGENTE' END AS VIGENCIA
FROM FIDE_MEMBRESIAS_TB M JOIN FIDE_SOCIOS_TB S ON S.ID_SOCIO = M.ID_SOCIO
JOIN FIDE_TIPOS_MEMBRESIA_TB T ON T.ID_TIPO_MEMBRESIA = M.ID_TIPO_MEMBRESIA;

CREATE OR REPLACE VIEW FIDE_INVENTARIOS_VW AS
SELECT I.ID_INVENTARIO, I.ID_PRODUCTO, P.CODIGO_PRODUCTO, P.NOMBRE, P.ID_CATEGORIA,
       I.CANTIDAD_MINIMA, NVL(M.EXISTENCIA, 0) AS CANTIDAD_DISPONIBLE,
       M.ULTIMO_MOVIMIENTO, P.ESTADO
FROM FIDE_INVENTARIOS_TB I JOIN FIDE_PRODUCTOS_TB P ON P.ID_PRODUCTO = I.ID_PRODUCTO
LEFT JOIN (SELECT ID_PRODUCTO, SUM(CASE WHEN TIPO_MOVIMIENTO='ENTRADA' THEN CANTIDAD ELSE -CANTIDAD END) EXISTENCIA,
                  MAX(FECHA_MOVIMIENTO) ULTIMO_MOVIMIENTO
           FROM FIDE_MOVIMIENTOS_INVENTARIO_TB GROUP BY ID_PRODUCTO) M ON M.ID_PRODUCTO=I.ID_PRODUCTO;

CREATE OR REPLACE VIEW FIDE_DETALLES_VENTA_VW AS
SELECT D.ID_DETALLE_VENTA, D.ID_VENTA, D.ID_PRODUCTO, P.CODIGO_PRODUCTO, P.NOMBRE,
       D.CANTIDAD, D.PRECIO_UNITARIO, D.CANTIDAD * D.PRECIO_UNITARIO AS SUBTOTAL
FROM FIDE_DETALLES_VENTA_TB D JOIN FIDE_PRODUCTOS_TB P ON P.ID_PRODUCTO=D.ID_PRODUCTO;

CREATE OR REPLACE VIEW FIDE_VENTAS_VW AS
SELECT V.ID_VENTA, V.ID_SOCIO, S.NOMBRE || ' ' || S.APELLIDOS AS SOCIO, V.ID_EMPLEADO,
       V.ID_TIPO_PAGO, P.NOMBRE AS TIPO_PAGO, V.FECHA_VENTA, V.FECHA_CONFIRMACION,
       V.ESTADO, V.ID_EMPLEADO_ANULACION, V.FECHA_ANULACION, V.MOTIVO_ANULACION, NVL(D.TOTAL,0) AS TOTAL
FROM FIDE_VENTAS_TB V JOIN FIDE_SOCIOS_TB S ON S.ID_SOCIO=V.ID_SOCIO
JOIN FIDE_TIPOS_PAGO_TB P ON P.ID_TIPO_PAGO=V.ID_TIPO_PAGO
LEFT JOIN (SELECT ID_VENTA, SUM(SUBTOTAL) TOTAL FROM FIDE_DETALLES_VENTA_VW GROUP BY ID_VENTA) D ON D.ID_VENTA=V.ID_VENTA;

CREATE OR REPLACE VIEW FIDE_PROVEEDORES_PRODUCTOS_VW AS
SELECT PP.ID_PROVEEDOR_PRODUCTO, PP.ID_PROVEEDOR, PR.NOMBRE AS PROVEEDOR,
       PP.ID_PRODUCTO, P.NOMBRE AS PRODUCTO, PP.PRECIO_COMPRA, PP.FECHA_ULTIMA_COMPRA,
       P.PRECIO_VENTA, P.PRECIO_VENTA-PP.PRECIO_COMPRA AS MARGEN_UNITARIO,
       PR.ESTADO AS ESTADO_PROVEEDOR, P.ESTADO AS ESTADO_PRODUCTO
FROM FIDE_PROVEEDORES_PRODUCTOS_TB PP JOIN FIDE_PROVEEDORES_TB PR ON PR.ID_PROVEEDOR=PP.ID_PROVEEDOR
JOIN FIDE_PRODUCTOS_TB P ON P.ID_PRODUCTO=PP.ID_PRODUCTO;

CREATE OR REPLACE VIEW FIDE_STOCK_BAJO_VW AS
SELECT ID_INVENTARIO, ID_PRODUCTO, CODIGO_PRODUCTO, NOMBRE, ID_CATEGORIA, CANTIDAD_MINIMA,
       CANTIDAD_DISPONIBLE, CANTIDAD_MINIMA-CANTIDAD_DISPONIBLE AS FALTANTE
FROM FIDE_INVENTARIOS_VW WHERE CANTIDAD_DISPONIBLE <= CANTIDAD_MINIMA AND ESTADO='ACTIVO';

CREATE OR REPLACE VIEW FIDE_VENTAS_DIARIAS_VW AS
SELECT TRUNC(FECHA_CONFIRMACION) AS DIA, COUNT(*) AS CANTIDAD_VENTAS, SUM(TOTAL) AS TOTAL
FROM FIDE_VENTAS_VW WHERE ESTADO='CONFIRMADA' GROUP BY TRUNC(FECHA_CONFIRMACION);

CREATE OR REPLACE VIEW FIDE_SOCIOS_RESUMEN_VW AS
SELECT S.ID_SOCIO, S.IDENTIFICACION, S.NOMBRE, S.APELLIDOS, S.ESTADO,
       NVL(V.CANTIDAD_VENTAS,0) AS CANTIDAD_VENTAS, NVL(V.TOTAL_COMPRAS,0) AS TOTAL_COMPRAS
FROM FIDE_SOCIOS_TB S LEFT JOIN (SELECT ID_SOCIO, COUNT(*) CANTIDAD_VENTAS, SUM(TOTAL) TOTAL_COMPRAS
FROM FIDE_VENTAS_VW WHERE ESTADO='CONFIRMADA' GROUP BY ID_SOCIO) V ON S.ID_SOCIO=V.ID_SOCIO;

CREATE OR REPLACE VIEW FIDE_PRODUCTOS_VENDIDOS_VW AS
SELECT P.ID_PRODUCTO, P.CODIGO_PRODUCTO, P.NOMBRE, SUM(D.CANTIDAD) AS UNIDADES_VENDIDAS,
       SUM(D.CANTIDAD*D.PRECIO_UNITARIO) AS TOTAL_VENDIDO
FROM FIDE_PRODUCTOS_TB P JOIN FIDE_DETALLES_VENTA_TB D ON D.ID_PRODUCTO=P.ID_PRODUCTO
JOIN FIDE_VENTAS_TB V ON V.ID_VENTA=D.ID_VENTA WHERE V.ESTADO='CONFIRMADA'
GROUP BY P.ID_PRODUCTO, P.CODIGO_PRODUCTO, P.NOMBRE;

CREATE OR REPLACE VIEW FIDE_USUARIOS_VW AS
SELECT U.ID_USUARIO, U.ID_EMPLEADO, E.NOMBRE || ' ' || E.APELLIDOS AS EMPLEADO,
       U.NOMBRE_USUARIO, U.ROL, U.ESTADO, E.ESTADO AS ESTADO_EMPLEADO
FROM FIDE_USUARIOS_SISTEMA_TB U JOIN FIDE_EMPLEADOS_TB E ON E.ID_EMPLEADO=U.ID_EMPLEADO;
