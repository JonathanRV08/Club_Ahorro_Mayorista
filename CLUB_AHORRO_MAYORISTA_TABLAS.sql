        (FECHA_CONFIRMACION IS NULL OR FECHA_CONFIRMACION >= FECHA_VENTA)
        AND (FECHA_ANULACION IS NULL OR FECHA_ANULACION >= FECHA_CONFIRMACION)
    ),
    CONSTRAINT FIDE_VENTAS_TB_CONFIRMACION_CK CHECK (
        (ESTADO = 'PENDIENTE' AND FECHA_CONFIRMACION IS NULL)
        OR (ESTADO IN ('CONFIRMADA', 'ANULADA') AND FECHA_CONFIRMACION IS NOT NULL)
    ),
    CONSTRAINT FIDE_VENTAS_TB_ANULACION_CK CHECK (
        (ESTADO = 'ANULADA' AND ID_EMPLEADO_ANULACION IS NOT NULL AND FECHA_ANULACION IS NOT NULL AND TRIM(MOTIVO_ANULACION) IS NOT NULL)
        OR (ESTADO IN ('PENDIENTE', 'CONFIRMADA') AND ID_EMPLEADO_ANULACION IS NULL AND FECHA_ANULACION IS NULL AND MOTIVO_ANULACION IS NULL)
    )
