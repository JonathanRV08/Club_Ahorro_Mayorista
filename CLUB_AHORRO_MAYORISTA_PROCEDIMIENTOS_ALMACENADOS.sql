            UPDATE FIDE_USUARIOS_SISTEMA_TB SET NOMBRE_USUARIO=LOWER(TRIM(P_NOMBRE_USUARIO)),
                HASH_CLAVE=NVL(P_HASH_CLAVE,HASH_CLAVE),ROL=P_ROL,ESTADO=NVL(P_ESTADO,ESTADO) WHERE ID_USUARIO=P_ID;
        WHEN 'D' THEN
            UPDATE FIDE_USUARIOS_SISTEMA_TB SET ESTADO='INACTIVO' WHERE ID_USUARIO=P_ID;
            IF SQL%ROWCOUNT=0 THEN RAISE_APPLICATION_ERROR(-20016,'Registro inexistente.'); END IF;
    END CASE;
    IF UPPER(TRIM(P_ACCION)) <> 'R' THEN
        OPEN P_RESULTADO FOR SELECT P_ID AS ID FROM DUAL WHERE 1=0;
    END IF;
EXCEPTION WHEN OTHERS THEN
    ROLLBACK TO SP_CRUD_USUARIOS_SISTEMA;
    RAISE;
END;
