CREATE OR REPLACE PROCEDURE FIDE_CRUD_MEMBRESIAS_PA (
    P_ACCION IN VARCHAR2,
    P_ID IN OUT FIDE_MEMBRESIAS_TB.ID_MEMBRESIA%TYPE,
    P_RESULTADO OUT SYS_REFCURSOR,
    P_ID_SOCIO IN FIDE_MEMBRESIAS_TB.ID_SOCIO%TYPE DEFAULT NULL,
    P_ID_TIPO_MEMBRESIA IN FIDE_MEMBRESIAS_TB.ID_TIPO_MEMBRESIA%TYPE DEFAULT NULL,
    P_FECHA_INICIO IN FIDE_MEMBRESIAS_TB.FECHA_INICIO%TYPE DEFAULT NULL
) IS
    V_SOCIO NUMBER;
    V_ESTADO VARCHAR2(15);
    V_FIN DATE;
BEGIN
    SAVEPOINT SP_CRUD_MEMBRESIAS;
    IF UPPER(TRIM(P_ACCION)) IS NULL OR UPPER(TRIM(P_ACCION)) NOT IN ('C','R','U','D') THEN
        RAISE_APPLICATION_ERROR(-20019,'Accion no valida. Use C, R, U o D.');
    END IF;
    IF UPPER(TRIM(P_ACCION)) IN ('U','D') AND P_ID IS NULL THEN
        RAISE_APPLICATION_ERROR(-20020,'El identificador es obligatorio.');
    END IF;
    CASE UPPER(TRIM(P_ACCION))
        WHEN 'C' THEN
            IF P_FECHA_INICIO IS NULL THEN RAISE_APPLICATION_ERROR(-20021,'Fecha de inicio obligatoria.'); END IF;
            FIDE_RENOVAR_MEMBRESIA_PA(P_ID_SOCIO,P_ID_TIPO_MEMBRESIA,P_FECHA_INICIO,P_ID);
        WHEN 'R' THEN
            OPEN P_RESULTADO FOR SELECT * FROM FIDE_MEMBRESIAS_VW WHERE (P_ID IS NULL OR ID_MEMBRESIA=P_ID) ORDER BY ID_MEMBRESIA;
        WHEN 'U' THEN
            SELECT ID_SOCIO,ESTADO INTO V_SOCIO,V_ESTADO FROM FIDE_MEMBRESIAS_TB WHERE ID_MEMBRESIA=P_ID;
            IF V_ESTADO<>'REGISTRADA' OR P_ID_SOCIO IS NULL OR V_SOCIO<>P_ID_SOCIO OR P_FECHA_INICIO IS NULL THEN
                RAISE_APPLICATION_ERROR(-20022,'No se puede cambiar el socio ni editar una membresia cancelada; indique fecha de inicio.');
            END IF;
            SELECT ID_SOCIO INTO V_SOCIO FROM FIDE_SOCIOS_TB WHERE ID_SOCIO=P_ID_SOCIO FOR UPDATE;
            SELECT ESTADO INTO V_ESTADO FROM FIDE_MEMBRESIAS_TB WHERE ID_MEMBRESIA=P_ID FOR UPDATE;
            IF V_ESTADO<>'REGISTRADA' THEN RAISE_APPLICATION_ERROR(-20022,'Membresia cancelada.'); END IF;
            IF FIDE_SOCIO_ACTIVO_FN(P_ID_SOCIO)=0 THEN RAISE_APPLICATION_ERROR(-20001,'Socio inactivo.'); END IF;
            V_FIN:=FIDE_FECHA_VENCIMIENTO_FN(P_ID_TIPO_MEMBRESIA,P_FECHA_INICIO);
            IF FIDE_MEMBRESIA_SOLAPADA_FN(P_ID_SOCIO,P_FECHA_INICIO,V_FIN,P_ID)=1 THEN
                RAISE_APPLICATION_ERROR(-20002,'Fechas superpuestas.');
            END IF;
            UPDATE FIDE_MEMBRESIAS_TB SET ID_TIPO_MEMBRESIA=P_ID_TIPO_MEMBRESIA,FECHA_INICIO=TRUNC(P_FECHA_INICIO),
                FECHA_VENCIMIENTO=V_FIN WHERE ID_MEMBRESIA=P_ID;
        WHEN 'D' THEN
            SELECT ID_SOCIO INTO V_SOCIO FROM FIDE_MEMBRESIAS_TB WHERE ID_MEMBRESIA=P_ID;
            SELECT ID_SOCIO INTO V_SOCIO FROM FIDE_SOCIOS_TB WHERE ID_SOCIO=V_SOCIO FOR UPDATE;
            UPDATE FIDE_MEMBRESIAS_TB SET ESTADO='CANCELADA' WHERE ID_MEMBRESIA=P_ID AND ESTADO='REGISTRADA';
            IF SQL%ROWCOUNT=0 THEN RAISE_APPLICATION_ERROR(-20022,'Membresia inexistente o cancelada.'); END IF;
    END CASE;
    IF UPPER(TRIM(P_ACCION)) <> 'R' THEN
        OPEN P_RESULTADO FOR SELECT P_ID AS ID FROM DUAL WHERE 1=0;
    END IF;
EXCEPTION WHEN OTHERS THEN
    ROLLBACK TO SP_CRUD_MEMBRESIAS;
    RAISE;
END;
