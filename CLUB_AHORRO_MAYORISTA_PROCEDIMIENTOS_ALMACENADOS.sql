CREATE OR REPLACE PROCEDURE FIDE_CRUD_MOVIMIENTOS_INVENTARIO_PA (
    P_ACCION IN VARCHAR2,
    P_ID IN OUT FIDE_MOVIMIENTOS_INVENTARIO_TB.ID_MOVIMIENTO%TYPE,
    P_RESULTADO OUT SYS_REFCURSOR,
    P_ID_PRODUCTO IN FIDE_MOVIMIENTOS_INVENTARIO_TB.ID_PRODUCTO%TYPE DEFAULT NULL,
    P_ID_EMPLEADO IN FIDE_MOVIMIENTOS_INVENTARIO_TB.ID_EMPLEADO%TYPE DEFAULT NULL,
    P_TIPO_MOVIMIENTO IN FIDE_MOVIMIENTOS_INVENTARIO_TB.TIPO_MOVIMIENTO%TYPE DEFAULT NULL,
    P_CANTIDAD IN FIDE_MOVIMIENTOS_INVENTARIO_TB.CANTIDAD%TYPE DEFAULT NULL,
    P_OBSERVACION IN FIDE_MOVIMIENTOS_INVENTARIO_TB.OBSERVACION%TYPE DEFAULT NULL
) IS
    V_ID NUMBER;
    V_PRODUCTO NUMBER;
BEGIN
    SAVEPOINT SP_CRUD_MOVIMIENTOS_INVENTARIO;
    IF UPPER(TRIM(P_ACCION)) IS NULL OR UPPER(TRIM(P_ACCION)) NOT IN ('C','R','U','D') THEN
        RAISE_APPLICATION_ERROR(-20019,'Accion no valida. Use C, R, U o D.');
    END IF;
    IF UPPER(TRIM(P_ACCION)) IN ('U','D') AND P_ID IS NULL THEN
        RAISE_APPLICATION_ERROR(-20020,'El identificador es obligatorio.');
    END IF;
    CASE UPPER(TRIM(P_ACCION))
        WHEN 'C' THEN
            SELECT ID_INVENTARIO INTO V_ID FROM FIDE_INVENTARIOS_TB WHERE ID_PRODUCTO=P_ID_PRODUCTO FOR UPDATE;
            IF FIDE_EMPLEADO_ACTIVO_FN(P_ID_EMPLEADO)=0 OR FIDE_PRODUCTO_ACTIVO_FN(P_ID_PRODUCTO)=0 THEN RAISE_APPLICATION_ERROR(-20017,'Producto o empleado inactivo.'); END IF;
            IF P_CANTIDAD IS NULL OR P_CANTIDAD<=0 OR P_CANTIDAD<>TRUNC(P_CANTIDAD) THEN RAISE_APPLICATION_ERROR(-20012,'Cantidad incorrecta.'); END IF;
            IF P_TIPO_MOVIMIENTO='SALIDA' AND FIDE_STOCK_FN(P_ID_PRODUCTO)<P_CANTIDAD THEN RAISE_APPLICATION_ERROR(-20007,'Existencias insuficientes.'); END IF;
            INSERT INTO FIDE_MOVIMIENTOS_INVENTARIO_TB(ID_PRODUCTO,ID_EMPLEADO,TIPO_MOVIMIENTO,CANTIDAD,OBSERVACION)
                VALUES(P_ID_PRODUCTO,P_ID_EMPLEADO,P_TIPO_MOVIMIENTO,P_CANTIDAD,P_OBSERVACION) RETURNING ID_MOVIMIENTO INTO P_ID;
        WHEN 'R' THEN
            OPEN P_RESULTADO FOR SELECT * FROM FIDE_MOVIMIENTOS_INVENTARIO_TB WHERE (P_ID IS NULL OR ID_MOVIMIENTO=P_ID) ORDER BY ID_MOVIMIENTO;
        WHEN 'U' THEN
            SELECT ID_PRODUCTO INTO V_PRODUCTO FROM FIDE_MOVIMIENTOS_INVENTARIO_TB WHERE ID_MOVIMIENTO=P_ID;
            IF P_ID_PRODUCTO IS NOT NULL AND P_ID_PRODUCTO<>V_PRODUCTO THEN RAISE_APPLICATION_ERROR(-20026,'No se cambia el producto del movimiento.'); END IF;
            FIDE_CORREGIR_MOVIMIENTO_PA(P_ID,P_ID_EMPLEADO,P_TIPO_MOVIMIENTO,P_CANTIDAD,P_OBSERVACION,V_ID);
            P_ID:=V_ID;
        WHEN 'D' THEN
            FIDE_REVERSAR_MOVIMIENTO_PA(P_ID,P_ID_EMPLEADO,P_OBSERVACION,V_ID);
    END CASE;
    IF UPPER(TRIM(P_ACCION)) <> 'R' THEN
        OPEN P_RESULTADO FOR SELECT P_ID AS ID FROM DUAL WHERE 1=0;
    END IF;
EXCEPTION WHEN OTHERS THEN
    ROLLBACK TO SP_CRUD_MOVIMIENTOS_INVENTARIO;
    RAISE;
END;
