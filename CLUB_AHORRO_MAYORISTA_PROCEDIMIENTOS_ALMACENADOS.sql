CREATE OR REPLACE PROCEDURE FIDE_REPORTE_PA (
    P_TIPO IN VARCHAR2, P_RESULTADO OUT SYS_REFCURSOR,
    P_ID IN NUMBER DEFAULT NULL, P_DESDE IN DATE DEFAULT NULL,
    P_HASTA IN DATE DEFAULT NULL, P_ESTADO IN VARCHAR2 DEFAULT NULL
) IS

BEGIN
    IF P_DESDE IS NOT NULL AND P_HASTA IS NOT NULL AND TRUNC(P_DESDE)>TRUNC(P_HASTA) THEN
        RAISE_APPLICATION_ERROR(-20013,'Intervalo de fechas incorrecto.');
    END IF;
    CASE UPPER(TRIM(P_TIPO))
        WHEN 'VENTAS' THEN
            OPEN P_RESULTADO FOR SELECT * FROM FIDE_VENTAS_VW WHERE ESTADO='CONFIRMADA' AND (P_ID IS NULL OR ID_SOCIO=P_ID) AND (P_DESDE IS NULL OR FECHA_CONFIRMACION>=TRUNC(P_DESDE)) AND (P_HASTA IS NULL OR FECHA_CONFIRMACION<TRUNC(P_HASTA)+1) ORDER BY FECHA_CONFIRMACION, ID_VENTA;
        WHEN 'VENTAS_DIARIAS' THEN
            OPEN P_RESULTADO FOR SELECT * FROM FIDE_VENTAS_DIARIAS_VW WHERE (P_DESDE IS NULL OR DIA>=TRUNC(P_DESDE)) AND (P_HASTA IS NULL OR DIA<=TRUNC(P_HASTA)) ORDER BY DIA;
        WHEN 'PRODUCTOS_VENDIDOS' THEN
            OPEN P_RESULTADO FOR SELECT * FROM FIDE_PRODUCTOS_VENDIDOS_VW WHERE (P_ID IS NULL OR ID_PRODUCTO=P_ID) ORDER BY UNIDADES_VENDIDAS DESC, ID_PRODUCTO;
        WHEN 'STOCK_BAJO' THEN
            OPEN P_RESULTADO FOR SELECT * FROM FIDE_STOCK_BAJO_VW WHERE (P_ID IS NULL OR ID_PRODUCTO=P_ID) ORDER BY FALTANTE DESC, ID_PRODUCTO;
        WHEN 'MEMBRESIAS' THEN
            OPEN P_RESULTADO FOR SELECT * FROM FIDE_MEMBRESIAS_VW WHERE (P_ID IS NULL OR ID_SOCIO=P_ID) AND (P_ESTADO IS NULL OR VIGENCIA=P_ESTADO) ORDER BY FECHA_VENCIMIENTO, ID_MEMBRESIA;
        WHEN 'PROXIMAS_VENCER' THEN
            OPEN P_RESULTADO FOR SELECT * FROM FIDE_MEMBRESIAS_VW WHERE VIGENCIA='VIGENTE' AND FECHA_VENCIMIENTO<TRUNC(SYSDATE)+31 AND (P_ID IS NULL OR ID_SOCIO=P_ID) ORDER BY FECHA_VENCIMIENTO;
        WHEN 'SOCIOS' THEN
            OPEN P_RESULTADO FOR SELECT * FROM FIDE_SOCIOS_RESUMEN_VW WHERE (P_ID IS NULL OR ID_SOCIO=P_ID) ORDER BY ID_SOCIO;
        WHEN 'PROVEEDORES' THEN
            OPEN P_RESULTADO FOR SELECT * FROM FIDE_PROVEEDORES_PRODUCTOS_VW WHERE (P_ID IS NULL OR ID_PROVEEDOR=P_ID) ORDER BY ID_PROVEEDOR, ID_PRODUCTO;
        WHEN 'INVENTARIO' THEN
            OPEN P_RESULTADO FOR SELECT * FROM FIDE_INVENTARIOS_VW WHERE (P_ID IS NULL OR ID_PRODUCTO=P_ID) ORDER BY ID_PRODUCTO;
        ELSE RAISE_APPLICATION_ERROR(-20014,'Reporte no reconocido.');
    END CASE;
END;
