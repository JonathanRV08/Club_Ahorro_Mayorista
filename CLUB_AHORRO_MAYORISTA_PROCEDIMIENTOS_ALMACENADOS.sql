        VALUES(M.ID_PRODUCTO,P_EMPLEADO,P_VENTA,'ENTRADA','ANULACION_VENTA',M.CANTIDAD,V_FECHA,'Reintegro por anulacion');
    END LOOP;
    UPDATE FIDE_VENTAS_TB SET ESTADO='ANULADA',ID_EMPLEADO_ANULACION=P_EMPLEADO,FECHA_ANULACION=V_FECHA,
        MOTIVO_ANULACION=P_MOTIVO WHERE ID_VENTA=P_VENTA;
EXCEPTION WHEN OTHERS THEN
    ROLLBACK TO SP_ANULAR_VENTA;
    RAISE;
END;
