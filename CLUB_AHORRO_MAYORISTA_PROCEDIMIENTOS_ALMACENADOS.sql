CREATE OR REPLACE PROCEDURE FIDE_RENOVAR_MEMBRESIA_PA (
    P_SOCIO IN NUMBER, P_TIPO IN NUMBER, P_INICIO IN DATE,
    P_ID OUT NUMBER
) IS
    V_INICIO DATE;
    V_FIN DATE;
    V_ULTIMA DATE;
    V_ESTADO FIDE_SOCIOS_TB.ESTADO%TYPE;
BEGIN
    SELECT ESTADO INTO V_ESTADO FROM FIDE_SOCIOS_TB WHERE ID_SOCIO=P_SOCIO FOR UPDATE;
    IF V_ESTADO<>'ACTIVO' THEN RAISE_APPLICATION_ERROR(-20001,'Socio inactivo.'); END IF;
    SELECT MAX(TRUNC(FECHA_VENCIMIENTO)) INTO V_ULTIMA FROM FIDE_MEMBRESIAS_TB
        WHERE ID_SOCIO=P_SOCIO AND ESTADO='REGISTRADA';
    V_INICIO := NVL(TRUNC(P_INICIO), GREATEST(TRUNC(SYSDATE), NVL(V_ULTIMA,TRUNC(SYSDATE))));
    V_FIN := FIDE_FECHA_VENCIMIENTO_FN(P_TIPO,V_INICIO);
    IF FIDE_MEMBRESIA_SOLAPADA_FN(P_SOCIO,V_INICIO,V_FIN)=1 THEN
        RAISE_APPLICATION_ERROR(-20002,'Existe una membresia con fechas superpuestas.');
    END IF;
    INSERT INTO FIDE_MEMBRESIAS_TB(ID_SOCIO,ID_TIPO_MEMBRESIA,FECHA_INICIO,FECHA_VENCIMIENTO)
        VALUES(P_SOCIO,P_TIPO,V_INICIO,V_FIN) RETURNING ID_MEMBRESIA INTO P_ID;
END;
