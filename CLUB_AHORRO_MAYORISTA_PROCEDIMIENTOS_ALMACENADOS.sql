CREATE OR REPLACE PROCEDURE FIDE_CONFIRMAR_VENTA_PA (
    P_VENTA IN NUMBER
) IS
    V_VENTA FIDE_VENTAS_TB%ROWTYPE;
    V_ID NUMBER;
    V_TOTAL NUMBER;
    V_ESTADO VARCHAR2(15);
    V_FECHA DATE := SYSDATE;

BEGIN
    SAVEPOINT SP_CONFIRMAR_VENTA;
    SELECT * INTO V_VENTA FROM FIDE_VENTAS_TB WHERE ID_VENTA=P_VENTA FOR UPDATE;
    IF V_VENTA.ESTADO<>'PENDIENTE' THEN RAISE_APPLICATION_ERROR(-20003,'La venta no esta pendiente.'); END IF;
    SELECT ESTADO INTO V_ESTADO FROM FIDE_SOCIOS_TB WHERE ID_SOCIO=V_VENTA.ID_SOCIO FOR UPDATE;
    IF V_ESTADO<>'ACTIVO' OR FIDE_MEMBRESIA_VIGENTE_FN(V_VENTA.ID_SOCIO,V_FECHA)=0 THEN
        RAISE_APPLICATION_ERROR(-20004,'El socio no tiene una membresia vigente.');
    END IF;
    IF FIDE_EMPLEADO_ACTIVO_FN(V_VENTA.ID_EMPLEADO)=0 OR FIDE_PAGO_ACTIVO_FN(V_VENTA.ID_TIPO_PAGO)=0 THEN
        RAISE_APPLICATION_ERROR(-20005,'Empleado o metodo de pago inactivo.');
    END IF;
    V_TOTAL := FIDE_TOTAL_VENTA_FN(P_VENTA);
    IF V_TOTAL<=0 THEN RAISE_APPLICATION_ERROR(-20006,'La venta no tiene detalles.'); END IF;
    FOR D IN (SELECT ID_PRODUCTO,CANTIDAD FROM FIDE_DETALLES_VENTA_TB
              WHERE ID_VENTA=P_VENTA ORDER BY ID_PRODUCTO) LOOP
        SELECT ID_INVENTARIO INTO V_ID FROM FIDE_INVENTARIOS_TB WHERE ID_PRODUCTO=D.ID_PRODUCTO FOR UPDATE;
        IF FIDE_PRODUCTO_ACTIVO_FN(D.ID_PRODUCTO)=0 OR FIDE_STOCK_FN(D.ID_PRODUCTO)<D.CANTIDAD THEN
            RAISE_APPLICATION_ERROR(-20007,'Producto inactivo o existencias insuficientes.');
        END IF;
        INSERT INTO FIDE_MOVIMIENTOS_INVENTARIO_TB(ID_PRODUCTO,ID_EMPLEADO,ID_VENTA,TIPO_MOVIMIENTO,ORIGEN,CANTIDAD,FECHA_MOVIMIENTO,OBSERVACION)
        VALUES(D.ID_PRODUCTO,V_VENTA.ID_EMPLEADO,P_VENTA,'SALIDA','VENTA',D.CANTIDAD,V_FECHA,'Salida por venta');
    END LOOP;
    UPDATE FIDE_VENTAS_TB SET ESTADO='CONFIRMADA', FECHA_CONFIRMACION=V_FECHA WHERE ID_VENTA=P_VENTA;
EXCEPTION WHEN OTHERS THEN
    ROLLBACK TO SP_CONFIRMAR_VENTA;
    RAISE;
END;
/
