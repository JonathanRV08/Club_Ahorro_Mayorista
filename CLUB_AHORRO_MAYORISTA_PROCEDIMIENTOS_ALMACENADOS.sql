CREATE OR REPLACE PROCEDURE FIDE_CRUD_VENTAS_PA (
    P_ACCION IN VARCHAR2,
    P_ID IN OUT FIDE_VENTAS_TB.ID_VENTA%TYPE,
    P_RESULTADO OUT SYS_REFCURSOR,
    P_ID_SOCIO IN FIDE_VENTAS_TB.ID_SOCIO%TYPE DEFAULT NULL,
    P_ID_EMPLEADO IN FIDE_VENTAS_TB.ID_EMPLEADO%TYPE DEFAULT NULL,
    P_ID_TIPO_PAGO IN FIDE_VENTAS_TB.ID_TIPO_PAGO%TYPE DEFAULT NULL,
    P_MOTIVO IN VARCHAR2 DEFAULT NULL
) IS
    V_ESTADO VARCHAR2(15);
BEGIN
    SAVEPOINT SP_CRUD_VENTAS;
    IF UPPER(TRIM(P_ACCION)) IS NULL OR UPPER(TRIM(P_ACCION)) NOT IN ('C','R','U','D') THEN
        RAISE_APPLICATION_ERROR(-20019,'Accion no valida. Use C, R, U o D.');
    END IF;
    IF UPPER(TRIM(P_ACCION)) IN ('U','D') AND P_ID IS NULL THEN
        RAISE_APPLICATION_ERROR(-20020,'El identificador es obligatorio.');
    END IF;
    CASE UPPER(TRIM(P_ACCION))
        WHEN 'C' THEN
            IF FIDE_SOCIO_ACTIVO_FN(P_ID_SOCIO)=0 OR FIDE_MEMBRESIA_VIGENTE_FN(P_ID_SOCIO)=0 THEN
                RAISE_APPLICATION_ERROR(-20004,'El socio no tiene una membresia vigente.'); END IF;
            IF FIDE_EMPLEADO_ACTIVO_FN(P_ID_EMPLEADO)=0 OR FIDE_PAGO_ACTIVO_FN(P_ID_TIPO_PAGO)=0 THEN
                RAISE_APPLICATION_ERROR(-20005,'Empleado o metodo de pago inactivo.'); END IF;
            INSERT INTO FIDE_VENTAS_TB(ID_SOCIO,ID_EMPLEADO,ID_TIPO_PAGO) VALUES(P_ID_SOCIO,P_ID_EMPLEADO,P_ID_TIPO_PAGO)
                RETURNING ID_VENTA INTO P_ID;
        WHEN 'R' THEN
            OPEN P_RESULTADO FOR SELECT * FROM FIDE_VENTAS_VW WHERE (P_ID IS NULL OR ID_VENTA=P_ID) ORDER BY ID_VENTA;
        WHEN 'U' THEN
            SELECT ESTADO INTO V_ESTADO FROM FIDE_VENTAS_TB WHERE ID_VENTA=P_ID FOR UPDATE;
            IF V_ESTADO<>'PENDIENTE' THEN RAISE_APPLICATION_ERROR(-20003,'La venta no esta pendiente.'); END IF;
            IF FIDE_SOCIO_ACTIVO_FN(P_ID_SOCIO)=0 OR FIDE_MEMBRESIA_VIGENTE_FN(P_ID_SOCIO)=0 THEN
                RAISE_APPLICATION_ERROR(-20004,'El socio no tiene una membresia vigente.'); END IF;
            IF FIDE_EMPLEADO_ACTIVO_FN(P_ID_EMPLEADO)=0 OR FIDE_PAGO_ACTIVO_FN(P_ID_TIPO_PAGO)=0 THEN
                RAISE_APPLICATION_ERROR(-20005,'Empleado o metodo de pago inactivo.'); END IF;
            UPDATE FIDE_VENTAS_TB SET ID_SOCIO=P_ID_SOCIO,ID_EMPLEADO=P_ID_EMPLEADO,ID_TIPO_PAGO=P_ID_TIPO_PAGO WHERE ID_VENTA=P_ID;
        WHEN 'D' THEN
            SELECT ESTADO INTO V_ESTADO FROM FIDE_VENTAS_TB WHERE ID_VENTA=P_ID FOR UPDATE;
            IF V_ESTADO='PENDIENTE' THEN
                DELETE FROM FIDE_DETALLES_VENTA_TB WHERE ID_VENTA=P_ID;
                DELETE FROM FIDE_VENTAS_TB WHERE ID_VENTA=P_ID;
            ELSIF V_ESTADO='CONFIRMADA' THEN
                FIDE_ANULAR_VENTA_PA(P_ID,P_ID_EMPLEADO,P_MOTIVO);
            ELSE RAISE_APPLICATION_ERROR(-20008,'La venta ya fue anulada.'); END IF;
    END CASE;
    IF UPPER(TRIM(P_ACCION)) <> 'R' THEN
        OPEN P_RESULTADO FOR SELECT P_ID AS ID FROM DUAL WHERE 1=0;
    END IF;
EXCEPTION WHEN OTHERS THEN
    ROLLBACK TO SP_CRUD_VENTAS;
    RAISE;
END;
