CREATE OR REPLACE PROCEDURE FIDE_CRUD_DETALLES_VENTA_PA (
    P_ACCION IN VARCHAR2,
    P_ID IN OUT FIDE_DETALLES_VENTA_TB.ID_DETALLE_VENTA%TYPE,
    P_RESULTADO OUT SYS_REFCURSOR,
    P_ID_VENTA IN FIDE_DETALLES_VENTA_TB.ID_VENTA%TYPE DEFAULT NULL,
    P_ID_PRODUCTO IN FIDE_DETALLES_VENTA_TB.ID_PRODUCTO%TYPE DEFAULT NULL,
    P_CANTIDAD IN FIDE_DETALLES_VENTA_TB.CANTIDAD%TYPE DEFAULT NULL
) IS
    V_VENTA NUMBER;
    V_PRODUCTO NUMBER;
    V_ESTADO VARCHAR2(15);
    V_PRECIO NUMBER;
BEGIN
    SAVEPOINT SP_CRUD_DETALLES_VENTA;
    IF UPPER(TRIM(P_ACCION)) IS NULL OR UPPER(TRIM(P_ACCION)) NOT IN ('C','R','U','D') THEN
        RAISE_APPLICATION_ERROR(-20019,'Accion no valida. Use C, R, U o D.');
    END IF;
    IF UPPER(TRIM(P_ACCION)) IN ('U','D') AND P_ID IS NULL THEN
        RAISE_APPLICATION_ERROR(-20020,'El identificador es obligatorio.');
    END IF;
    CASE UPPER(TRIM(P_ACCION))
        WHEN 'C' THEN
            SELECT ESTADO INTO V_ESTADO FROM FIDE_VENTAS_TB WHERE ID_VENTA=P_ID_VENTA FOR UPDATE;
            IF V_ESTADO<>'PENDIENTE' THEN RAISE_APPLICATION_ERROR(-20003,'La venta no esta pendiente.'); END IF;
            IF P_CANTIDAD IS NULL OR P_CANTIDAD<=0 OR P_CANTIDAD<>TRUNC(P_CANTIDAD) THEN RAISE_APPLICATION_ERROR(-20012,'Cantidad incorrecta.'); END IF;
            IF FIDE_STOCK_FN(P_ID_PRODUCTO)<P_CANTIDAD THEN RAISE_APPLICATION_ERROR(-20007,'Existencias insuficientes.'); END IF;
            V_PRECIO:=FIDE_PRECIO_PRODUCTO_FN(P_ID_PRODUCTO);
            INSERT INTO FIDE_DETALLES_VENTA_TB(ID_VENTA,ID_PRODUCTO,CANTIDAD,PRECIO_UNITARIO)
                VALUES(P_ID_VENTA,P_ID_PRODUCTO,P_CANTIDAD,V_PRECIO) RETURNING ID_DETALLE_VENTA INTO P_ID;
        WHEN 'R' THEN
            OPEN P_RESULTADO FOR SELECT * FROM FIDE_DETALLES_VENTA_VW WHERE (P_ID IS NULL OR ID_DETALLE_VENTA=P_ID) ORDER BY ID_DETALLE_VENTA;
        WHEN 'U' THEN
            SELECT ID_VENTA,ID_PRODUCTO INTO V_VENTA,V_PRODUCTO FROM FIDE_DETALLES_VENTA_TB WHERE ID_DETALLE_VENTA=P_ID;
            SELECT ESTADO INTO V_ESTADO FROM FIDE_VENTAS_TB WHERE ID_VENTA=V_VENTA FOR UPDATE;
            IF V_ESTADO<>'PENDIENTE' OR (P_ID_VENTA IS NOT NULL AND P_ID_VENTA<>V_VENTA) THEN RAISE_APPLICATION_ERROR(-20003,'La venta no esta pendiente o no coincide.'); END IF;
            IF P_CANTIDAD IS NULL OR P_CANTIDAD<=0 OR P_CANTIDAD<>TRUNC(P_CANTIDAD) THEN RAISE_APPLICATION_ERROR(-20012,'Cantidad incorrecta.'); END IF;
            V_PRODUCTO:=NVL(P_ID_PRODUCTO,V_PRODUCTO);
            IF FIDE_STOCK_FN(V_PRODUCTO)<P_CANTIDAD THEN RAISE_APPLICATION_ERROR(-20007,'Existencias insuficientes.'); END IF;
            V_PRECIO:=FIDE_PRECIO_PRODUCTO_FN(V_PRODUCTO);
            UPDATE FIDE_DETALLES_VENTA_TB SET ID_PRODUCTO=V_PRODUCTO,CANTIDAD=P_CANTIDAD,PRECIO_UNITARIO=V_PRECIO WHERE ID_DETALLE_VENTA=P_ID;
            IF SQL%ROWCOUNT=0 THEN RAISE_APPLICATION_ERROR(-20016,'Detalle inexistente.'); END IF;
        WHEN 'D' THEN
            SELECT ID_VENTA INTO V_VENTA FROM FIDE_DETALLES_VENTA_TB WHERE ID_DETALLE_VENTA=P_ID;
            SELECT ESTADO INTO V_ESTADO FROM FIDE_VENTAS_TB WHERE ID_VENTA=V_VENTA FOR UPDATE;
            IF V_ESTADO<>'PENDIENTE' THEN RAISE_APPLICATION_ERROR(-20003,'La venta no esta pendiente.'); END IF;
            DELETE FROM FIDE_DETALLES_VENTA_TB WHERE ID_DETALLE_VENTA=P_ID;
            IF SQL%ROWCOUNT=0 THEN RAISE_APPLICATION_ERROR(-20016,'Detalle inexistente.'); END IF;
    END CASE;
    IF UPPER(TRIM(P_ACCION)) <> 'R' THEN
        OPEN P_RESULTADO FOR SELECT P_ID AS ID FROM DUAL WHERE 1=0;
    END IF;
EXCEPTION WHEN OTHERS THEN
    ROLLBACK TO SP_CRUD_DETALLES_VENTA;
    RAISE;
END;
