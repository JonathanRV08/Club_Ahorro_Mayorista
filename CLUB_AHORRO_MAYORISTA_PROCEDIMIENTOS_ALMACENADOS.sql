CREATE OR REPLACE PROCEDURE FIDE_REVERSAR_MOVIMIENTO_PA (
    P_MOVIMIENTO IN NUMBER, P_EMPLEADO IN NUMBER, P_MOTIVO IN VARCHAR2, P_ID OUT NUMBER
) IS
    V_M FIDE_MOVIMIENTOS_INVENTARIO_TB%ROWTYPE;
    V_ID NUMBER;
    V_TIPO VARCHAR2(10);
    V_TOTAL NUMBER;
BEGIN
    SELECT * INTO V_M FROM FIDE_MOVIMIENTOS_INVENTARIO_TB WHERE ID_MOVIMIENTO=P_MOVIMIENTO;
    SELECT ID_INVENTARIO INTO V_ID FROM FIDE_INVENTARIOS_TB WHERE ID_PRODUCTO=V_M.ID_PRODUCTO FOR UPDATE;
    IF V_M.ORIGEN<>'MANUAL' THEN RAISE_APPLICATION_ERROR(-20010,'Solo se revierten movimientos manuales.'); END IF;
    SELECT COUNT(*) INTO V_TOTAL FROM FIDE_MOVIMIENTOS_INVENTARIO_TB WHERE ID_MOVIMIENTO_ORIGEN=P_MOVIMIENTO;
    IF V_TOTAL>0 THEN RAISE_APPLICATION_ERROR(-20011,'El movimiento ya fue revertido.'); END IF;
    IF FIDE_EMPLEADO_ACTIVO_FN(P_EMPLEADO)=0 OR TRIM(P_MOTIVO) IS NULL THEN
        RAISE_APPLICATION_ERROR(-20009,'Empleado inactivo o motivo obligatorio.');
    END IF;
    V_TIPO := CASE V_M.TIPO_MOVIMIENTO WHEN 'ENTRADA' THEN 'SALIDA' ELSE 'ENTRADA' END;
    IF V_TIPO='SALIDA' AND FIDE_STOCK_FN(V_M.ID_PRODUCTO)<V_M.CANTIDAD THEN
        RAISE_APPLICATION_ERROR(-20007,'Existencias insuficientes para revertir.');
    END IF;
    INSERT INTO FIDE_MOVIMIENTOS_INVENTARIO_TB(ID_PRODUCTO,ID_EMPLEADO,ID_MOVIMIENTO_ORIGEN,TIPO_MOVIMIENTO,ORIGEN,CANTIDAD,OBSERVACION)
    VALUES(V_M.ID_PRODUCTO,P_EMPLEADO,P_MOVIMIENTO,V_TIPO,'REVERSO_MANUAL',V_M.CANTIDAD,P_MOTIVO)
    RETURNING ID_MOVIMIENTO INTO P_ID;
END;
