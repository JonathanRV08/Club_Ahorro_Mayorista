CREATE OR REPLACE PROCEDURE FIDE_ANULAR_VENTA_PA (
    P_VENTA IN NUMBER, P_EMPLEADO IN NUMBER, P_MOTIVO IN VARCHAR2
) IS
    V_ESTADO VARCHAR2(15);
    V_ID NUMBER;
    V_FECHA DATE := SYSDATE;

BEGIN
    SAVEPOINT SP_ANULAR_VENTA;
    SELECT ESTADO INTO V_ESTADO FROM FIDE_VENTAS_TB WHERE ID_VENTA=P_VENTA FOR UPDATE;
    IF V_ESTADO<>'CONFIRMADA' THEN RAISE_APPLICATION_ERROR(-20008,'Solo se anulan ventas confirmadas.'); END IF;
    IF FIDE_EMPLEADO_ACTIVO_FN(P_EMPLEADO)=0 OR TRIM(P_MOTIVO) IS NULL THEN
        RAISE_APPLICATION_ERROR(-20009,'Empleado inactivo o motivo obligatorio.');
    END IF;
    FOR M IN (SELECT ID_PRODUCTO,CANTIDAD FROM FIDE_MOVIMIENTOS_INVENTARIO_TB
              WHERE ID_VENTA=P_VENTA AND ORIGEN='VENTA' ORDER BY ID_PRODUCTO) LOOP
        SELECT ID_INVENTARIO INTO V_ID FROM FIDE_INVENTARIOS_TB WHERE ID_PRODUCTO=M.ID_PRODUCTO FOR UPDATE;
