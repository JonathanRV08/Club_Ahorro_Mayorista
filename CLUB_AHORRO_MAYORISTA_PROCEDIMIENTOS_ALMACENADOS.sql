CREATE OR REPLACE PROCEDURE FIDE_CRUD_SOCIOS_PA (
    P_ACCION IN VARCHAR2,
    P_ID IN OUT FIDE_SOCIOS_TB.ID_SOCIO%TYPE,
    P_RESULTADO OUT SYS_REFCURSOR,
    P_IDENTIFICACION IN FIDE_SOCIOS_TB.IDENTIFICACION%TYPE DEFAULT NULL,
    P_NOMBRE IN FIDE_SOCIOS_TB.NOMBRE%TYPE DEFAULT NULL,
    P_APELLIDOS IN FIDE_SOCIOS_TB.APELLIDOS%TYPE DEFAULT NULL,
    P_TELEFONO IN FIDE_SOCIOS_TB.TELEFONO%TYPE DEFAULT NULL,
    P_CORREO IN FIDE_SOCIOS_TB.CORREO%TYPE DEFAULT NULL,
    P_FECHA_REGISTRO IN FIDE_SOCIOS_TB.FECHA_REGISTRO%TYPE DEFAULT NULL,
    P_ESTADO IN FIDE_SOCIOS_TB.ESTADO%TYPE DEFAULT NULL
) IS

BEGIN
    SAVEPOINT SP_CRUD_SOCIOS;
    IF UPPER(TRIM(P_ACCION)) IS NULL OR UPPER(TRIM(P_ACCION)) NOT IN ('C','R','U','D') THEN
        RAISE_APPLICATION_ERROR(-20019,'Accion no valida. Use C, R, U o D.');
    END IF;
    IF UPPER(TRIM(P_ACCION)) IN ('U','D') AND P_ID IS NULL THEN
        RAISE_APPLICATION_ERROR(-20020,'El identificador es obligatorio.');
    END IF;
    CASE UPPER(TRIM(P_ACCION))
        WHEN 'C' THEN
            INSERT INTO FIDE_SOCIOS_TB(IDENTIFICACION,NOMBRE,APELLIDOS,TELEFONO,CORREO,FECHA_REGISTRO,ESTADO)
            VALUES(P_IDENTIFICACION,P_NOMBRE,P_APELLIDOS,P_TELEFONO,P_CORREO,NVL(P_FECHA_REGISTRO,SYSDATE),NVL(P_ESTADO,'ACTIVO')) RETURNING ID_SOCIO INTO P_ID;
        WHEN 'R' THEN
            OPEN P_RESULTADO FOR SELECT * FROM FIDE_SOCIOS_TB WHERE (P_ID IS NULL OR ID_SOCIO=P_ID) ORDER BY ID_SOCIO;
        WHEN 'U' THEN
            UPDATE FIDE_SOCIOS_TB SET IDENTIFICACION=P_IDENTIFICACION, NOMBRE=P_NOMBRE, APELLIDOS=P_APELLIDOS, TELEFONO=P_TELEFONO, CORREO=P_CORREO, FECHA_REGISTRO=NVL(P_FECHA_REGISTRO,FECHA_REGISTRO), ESTADO=NVL(P_ESTADO,ESTADO) WHERE ID_SOCIO=P_ID;
            IF SQL%ROWCOUNT=0 THEN RAISE_APPLICATION_ERROR(-20016,'Registro inexistente.'); END IF;
        WHEN 'D' THEN
            UPDATE FIDE_SOCIOS_TB SET ESTADO='INACTIVO' WHERE ID_SOCIO=P_ID;
            IF SQL%ROWCOUNT=0 THEN RAISE_APPLICATION_ERROR(-20016,'Registro inexistente.'); END IF;
    END CASE;
    IF UPPER(TRIM(P_ACCION)) <> 'R' THEN
        OPEN P_RESULTADO FOR SELECT P_ID AS ID FROM DUAL WHERE 1=0;
    END IF;
EXCEPTION WHEN OTHERS THEN
    ROLLBACK TO SP_CRUD_SOCIOS;
    RAISE;
END;
/
