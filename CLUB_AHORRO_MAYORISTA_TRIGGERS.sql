CREATE OR REPLACE TRIGGER FIDE_MEMBRESIAS_TRG
FOR INSERT OR UPDATE ON FIDE_MEMBRESIAS_TB
COMPOUND TRIGGER
    TYPE T_IDS IS TABLE OF NUMBER INDEX BY PLS_INTEGER;
    G_IDS T_IDS;
    G_N PLS_INTEGER := 0;

    BEFORE EACH ROW IS
        V_ID NUMBER;
    BEGIN
        IF UPDATING AND :OLD.ID_SOCIO<>:NEW.ID_SOCIO THEN
            RAISE_APPLICATION_ERROR(-20022,'No se cambia el socio de una membresia.');
        END IF;
        SELECT ID_SOCIO INTO V_ID FROM FIDE_SOCIOS_TB WHERE ID_SOCIO=:NEW.ID_SOCIO FOR UPDATE;
        IF :NEW.ESTADO='REGISTRADA' THEN
            G_N:=G_N+1;
            G_IDS(G_N):=:NEW.ID_MEMBRESIA;
        END IF;
    END BEFORE EACH ROW;

    AFTER STATEMENT IS
        V_SOCIO NUMBER;
        V_INICIO DATE;
        V_FIN DATE;
    BEGIN
        FOR I IN 1..G_N LOOP
            SELECT ID_SOCIO,FECHA_INICIO,FECHA_VENCIMIENTO INTO V_SOCIO,V_INICIO,V_FIN
                FROM FIDE_MEMBRESIAS_TB WHERE ID_MEMBRESIA=G_IDS(I);
            IF FIDE_MEMBRESIA_SOLAPADA_FN(V_SOCIO,V_INICIO,V_FIN,G_IDS(I))=1 THEN
                RAISE_APPLICATION_ERROR(-20002,'Membresias superpuestas.');
            END IF;
        END LOOP;
    END AFTER STATEMENT;
END FIDE_MEMBRESIAS_TRG;
/
SHOW ERRORS TRIGGER FIDE_MEMBRESIAS_TRG;

CREATE OR REPLACE TRIGGER FIDE_DETALLES_VENTA_TRG
BEFORE INSERT OR UPDATE OR DELETE ON FIDE_DETALLES_VENTA_TB
FOR EACH ROW
DECLARE
    V_VENTA NUMBER;
    V_ESTADO VARCHAR2(15);
BEGIN
    IF UPDATING AND :OLD.ID_VENTA<>:NEW.ID_VENTA THEN
        RAISE_APPLICATION_ERROR(-20003,'No se traslada un detalle a otra venta.');
    END IF;
    IF DELETING THEN V_VENTA:=:OLD.ID_VENTA; ELSE V_VENTA:=:NEW.ID_VENTA; END IF;
    SELECT ESTADO INTO V_ESTADO FROM FIDE_VENTAS_TB WHERE ID_VENTA=V_VENTA FOR UPDATE;
    IF V_ESTADO<>'PENDIENTE' THEN
        RAISE_APPLICATION_ERROR(-20003,'Solo se editan detalles de ventas pendientes.');
    END IF;
END;
/
SHOW ERRORS TRIGGER FIDE_DETALLES_VENTA_TRG;

CREATE OR REPLACE TRIGGER FIDE_VENTAS_TRG
BEFORE INSERT OR UPDATE OR DELETE ON FIDE_VENTAS_TB
FOR EACH ROW
DECLARE
    V_DETALLES NUMBER;
    V_MOVIMIENTOS NUMBER;
BEGIN
    IF INSERTING THEN
        IF :NEW.ESTADO<>'PENDIENTE' THEN RAISE_APPLICATION_ERROR(-20027,'Una venta nueva debe estar pendiente.'); END IF;
    ELSIF DELETING THEN
        IF :OLD.ESTADO<>'PENDIENTE' THEN RAISE_APPLICATION_ERROR(-20027,'No se elimina una venta historica.'); END IF;
    ELSE
        IF :NEW.ID_VENTA<>:OLD.ID_VENTA OR :NEW.FECHA_VENTA<>:OLD.FECHA_VENTA THEN
            RAISE_APPLICATION_ERROR(-20027,'No se modifica el identificador ni la fecha de apertura.');
        END IF;
        IF :OLD.ESTADO='ANULADA' OR (:OLD.ESTADO='CONFIRMADA' AND :NEW.ESTADO<>'ANULADA') OR
           (:OLD.ESTADO='PENDIENTE' AND :NEW.ESTADO='ANULADA') THEN
            RAISE_APPLICATION_ERROR(-20027,'Transicion de venta no permitida.');
        END IF;
        IF :NEW.ESTADO IN ('CONFIRMADA','ANULADA') THEN
            IF :NEW.ID_SOCIO<>:OLD.ID_SOCIO OR :NEW.ID_EMPLEADO<>:OLD.ID_EMPLEADO OR
               :NEW.ID_TIPO_PAGO<>:OLD.ID_TIPO_PAGO THEN
                RAISE_APPLICATION_ERROR(-20027,'No se cambia el encabezado de una venta al cerrarla.');
            END IF;
            SELECT COUNT(*) INTO V_DETALLES FROM FIDE_DETALLES_VENTA_TB WHERE ID_VENTA=:OLD.ID_VENTA;
            IF :NEW.ESTADO='CONFIRMADA' THEN
                IF FIDE_SOCIO_ACTIVO_FN(:NEW.ID_SOCIO)=0 OR FIDE_MEMBRESIA_VIGENTE_FN(:NEW.ID_SOCIO,:NEW.FECHA_CONFIRMACION)=0
                   OR FIDE_EMPLEADO_ACTIVO_FN(:NEW.ID_EMPLEADO)=0 OR FIDE_PAGO_ACTIVO_FN(:NEW.ID_TIPO_PAGO)=0 THEN
                    RAISE_APPLICATION_ERROR(-20004,'Venta sin socio, membresia, empleado o pago habilitado.');
                END IF;
                SELECT COUNT(*) INTO V_MOVIMIENTOS FROM FIDE_MOVIMIENTOS_INVENTARIO_TB M JOIN FIDE_DETALLES_VENTA_TB D
                    ON D.ID_VENTA=M.ID_VENTA AND D.ID_PRODUCTO=M.ID_PRODUCTO AND D.CANTIDAD=M.CANTIDAD
                    WHERE M.ID_VENTA=:OLD.ID_VENTA AND M.ORIGEN='VENTA' AND M.ID_EMPLEADO=:NEW.ID_EMPLEADO;
            ELSE
                IF :NEW.FECHA_CONFIRMACION<>:OLD.FECHA_CONFIRMACION OR FIDE_EMPLEADO_ACTIVO_FN(:NEW.ID_EMPLEADO_ANULACION)=0 THEN
                    RAISE_APPLICATION_ERROR(-20027,'Fecha de confirmacion o empleado de anulacion incorrectos.');
                END IF;
                SELECT COUNT(*) INTO V_MOVIMIENTOS FROM FIDE_MOVIMIENTOS_INVENTARIO_TB M JOIN FIDE_DETALLES_VENTA_TB D
                    ON D.ID_VENTA=M.ID_VENTA AND D.ID_PRODUCTO=M.ID_PRODUCTO AND D.CANTIDAD=M.CANTIDAD
                    WHERE M.ID_VENTA=:OLD.ID_VENTA AND M.ORIGEN='ANULACION_VENTA' AND M.ID_EMPLEADO=:NEW.ID_EMPLEADO_ANULACION;
            END IF;
            IF V_DETALLES=0 OR V_DETALLES<>V_MOVIMIENTOS THEN
                RAISE_APPLICATION_ERROR(-20028,'Faltan movimientos de inventario para cerrar la venta.');
            END IF;
        END IF;
    END IF;
END;
/
SHOW ERRORS TRIGGER FIDE_VENTAS_TRG;

CREATE OR REPLACE TRIGGER FIDE_MOVIMIENTOS_INV_TRG
FOR INSERT OR UPDATE OR DELETE ON FIDE_MOVIMIENTOS_INVENTARIO_TB
COMPOUND TRIGGER
    TYPE T_IDS IS TABLE OF NUMBER INDEX BY PLS_INTEGER;
    G_PRODUCTOS T_IDS;
    G_MOVIMIENTOS T_IDS;
    G_N PLS_INTEGER := 0;

    BEFORE EACH ROW IS
        V_ID NUMBER;
        V_ESTADO VARCHAR2(15);
        V_CANTIDAD NUMBER;
        V_EMPLEADO NUMBER;
    BEGIN
        IF UPDATING OR DELETING THEN
            RAISE_APPLICATION_ERROR(-20029,'El historial de inventario se corrige mediante reversos.');
        END IF;
        IF :NEW.ID_VENTA IS NOT NULL THEN
            SELECT ESTADO,ID_EMPLEADO INTO V_ESTADO,V_EMPLEADO FROM FIDE_VENTAS_TB
                WHERE ID_VENTA=:NEW.ID_VENTA FOR UPDATE;
            IF (:NEW.ORIGEN='VENTA' AND (V_ESTADO<>'PENDIENTE' OR V_EMPLEADO<>:NEW.ID_EMPLEADO)) OR
               (:NEW.ORIGEN='ANULACION_VENTA' AND V_ESTADO<>'CONFIRMADA') THEN
                RAISE_APPLICATION_ERROR(-20027,'Movimiento incompatible con el estado de la venta.');
            END IF;
            SELECT CANTIDAD INTO V_CANTIDAD FROM FIDE_DETALLES_VENTA_TB
                WHERE ID_VENTA=:NEW.ID_VENTA AND ID_PRODUCTO=:NEW.ID_PRODUCTO;
            IF V_CANTIDAD<>:NEW.CANTIDAD THEN RAISE_APPLICATION_ERROR(-20028,'Cantidad distinta del detalle.'); END IF;
        END IF;
        SELECT ID_INVENTARIO INTO V_ID FROM FIDE_INVENTARIOS_TB WHERE ID_PRODUCTO=:NEW.ID_PRODUCTO FOR UPDATE;
        IF FIDE_EMPLEADO_ACTIVO_FN(:NEW.ID_EMPLEADO)=0 THEN RAISE_APPLICATION_ERROR(-20017,'Empleado inactivo.'); END IF;
        G_N:=G_N+1;
        G_PRODUCTOS(G_N):=:NEW.ID_PRODUCTO;
        G_MOVIMIENTOS(G_N):=:NEW.ID_MOVIMIENTO;
    END BEFORE EACH ROW;

    AFTER STATEMENT IS
        V_M FIDE_MOVIMIENTOS_INVENTARIO_TB%ROWTYPE;
        V_O FIDE_MOVIMIENTOS_INVENTARIO_TB%ROWTYPE;
    BEGIN
        FOR I IN 1..G_N LOOP
            IF FIDE_STOCK_FN(G_PRODUCTOS(I))<0 THEN RAISE_APPLICATION_ERROR(-20007,'El inventario no puede ser negativo.'); END IF;
            SELECT * INTO V_M FROM FIDE_MOVIMIENTOS_INVENTARIO_TB WHERE ID_MOVIMIENTO=G_MOVIMIENTOS(I);
            IF V_M.ORIGEN='REVERSO_MANUAL' THEN
                SELECT * INTO V_O FROM FIDE_MOVIMIENTOS_INVENTARIO_TB WHERE ID_MOVIMIENTO=V_M.ID_MOVIMIENTO_ORIGEN;
                IF V_O.ORIGEN<>'MANUAL' OR V_M.ID_PRODUCTO<>V_O.ID_PRODUCTO OR
                   V_M.CANTIDAD<>V_O.CANTIDAD OR V_M.TIPO_MOVIMIENTO=V_O.TIPO_MOVIMIENTO THEN
                    RAISE_APPLICATION_ERROR(-20010,'Reverso incompatible con el movimiento original.');
                END IF;
            END IF;
        END LOOP;
    END AFTER STATEMENT;
END FIDE_MOVIMIENTOS_INV_TRG;
/
SHOW ERRORS TRIGGER FIDE_MOVIMIENTOS_INV_TRG;

CREATE OR REPLACE TRIGGER FIDE_EMPLEADOS_TRG
AFTER UPDATE OF ESTADO ON FIDE_EMPLEADOS_TB
FOR EACH ROW
BEGIN
    IF :OLD.ESTADO='ACTIVO' AND :NEW.ESTADO='INACTIVO' THEN
        UPDATE FIDE_USUARIOS_SISTEMA_TB SET ESTADO='INACTIVO' WHERE ID_EMPLEADO=:NEW.ID_EMPLEADO;
    END IF;
END;
/
SHOW ERRORS TRIGGER FIDE_EMPLEADOS_TRG;
